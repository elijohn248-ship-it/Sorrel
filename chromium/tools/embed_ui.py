#!/usr/bin/env python3
"""Builds Birch's own UI pages (chromium/ui/web/) into the app.

  python3 -I embed_ui.py <ui/web folder> <out .cc>

Writes a C++ file holding every .html/.css/.js/.svg/.png/.woff2 file under the
folder as a byte array, for engine/cef/ui_scheme.cc to serve under
birch-ui://. The pages are compiled into the binary, so they can never come
from the network or the profile, and nothing on disk can swap them. Other
files (README.md, .gitkeep) are left out.
"""
import os
import sys

TYPES = {
    ".html": "text/html",
    ".css": "text/css",
    ".js": "text/javascript",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".woff2": "font/woff2",
}


def main():
    src, out = sys.argv[1], sys.argv[2]
    files = []
    for d, dirs, names in os.walk(src):
        dirs[:] = sorted(x for x in dirs if not x.startswith("."))
        for n in sorted(names):
            ext = os.path.splitext(n)[1].lower()
            if n.startswith(".") or ext not in TYPES:
                continue
            path = os.path.join(d, n)
            rel = os.path.relpath(path, src).replace(os.sep, "/")
            if not all(c.isalnum() or c in "-_./" for c in rel) or ".." in rel:
                sys.exit(f"embed_ui: refusing odd file name {rel!r}")
            with open(path, "rb") as f:
                files.append((rel, f.read(), TYPES[ext]))
    lines = ["// Generated by tools/embed_ui.py from chromium/ui/web/. Do not edit.",
             '#include "engine/cef/ui_resources.h"', "",
             "namespace birch::engine::ui_resources {", "", "namespace {", ""]
    for i, (_rel, data, _t) in enumerate(files):
        body = ",".join(str(b) for b in data) or "0"
        lines.append(f"const unsigned char k{i}[] = {{{body}}};")
    lines += ["", "const Resource kAll[] = {"]
    for i, (rel, data, mime) in enumerate(files):
        lines.append(f'    {{"{rel}", k{i}, {len(data)}u, "{mime}"}},')
    lines += ["};", "", "}  // namespace", "",
              "const Resource* Find(const std::string& path) {",
              "  for (const Resource& r : kAll) {",
              "    if (path == r.path) {",
              "      return &r;",
              "    }",
              "  }",
              "  return nullptr;",
              "}", "",
              f"size_t Count() {{ return {len(files)}u; }}", "",
              "}  // namespace birch::engine::ui_resources", ""]
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    text = "\n".join(lines)
    if os.path.exists(out) and open(out, encoding="utf-8").read() == text:
        return
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"embed_ui: {len(files)} files, {sum(len(d) for _, d, _ in files)} bytes")


if __name__ == "__main__":
    main()
